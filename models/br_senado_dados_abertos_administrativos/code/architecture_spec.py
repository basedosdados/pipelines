"""
Single source of truth for br_senado_dados_abertos_administrativos.

Drives (a) dbt SQL generation, (b) dbt schema.yml (PT descriptions), and
(c) backend column registration (PT/EN/ES). Column order here is the table's
column order, and follows the house rule: partition columns first (temporal,
then geographic), then identifiers, then descriptive columns.

Each column: (name, type, pt, en, es[, opts])
  type: "str" | "int" | "float" | "date" | "datetime"
  opts: dict with any of:
    part=True         partition column
    notnull=True      add dbt not_null test (partition / key columns)
    dir="ds.tbl:col"  directory_column FK
    dict=True         covered_by_dictionary
    unit="BRL"        measurement_unit (required on every numeric quantity)

Two partition schemes are in play, per the source's own shape:
  * `ano`            — the four genuine time series (CEAPS 2008+, remunerações
                       2013+, horas extras 2013+, supridos 2013+)
  * `data_extracao`  — everything else. The API exposes only current state with
                       no time dimension, so snapshots are stacked, as in
                       br_cgu_sancoes and au_ato_abr.
"""

