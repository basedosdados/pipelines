"""Write the architecture CSVs for us_dot_fars.

The CSVs under ``architecture/`` are the single source of truth for column names,
order, types, descriptions and the raw -> clean mapping. The cleaning transform,
the dbt models and the backend metadata payloads are all generated from them, so
the four cannot describe different schemas.

``original_name`` holds a ``|``-separated list of source aliases, newest first.
FARS renamed variables repeatedly over 50 years (TEST_RES -> ALC_RES,
C_M_ZONE -> WRK_ZONE, REL_JUNC -> RELJCT2); the transform takes the first alias
present in that year's header. A column whose concept was genuinely restructured
rather than renamed keeps its own entry with its own temporal coverage, because
merging incompatible code sets under one name would be a correctness bug.

Run: uv run python models/us_dot_fars/code/gen_architecture.py
"""

