TABLES = {
    "crash": CRASH,
    "vehicle": VEHICLE,
    "person": PERSON,
    "dicionario": DICIONARIO,
}


def main() -> None:
    ARCH.mkdir(parents=True, exist_ok=True)
    for table, cols in TABLES.items():
        names = [c["name"] for c in cols]
        assert len(names) == len(set(names)), (
            f"{table}: duplicate column names"
        )
        for col in cols:
            if col["bigquery_type"] in ("INT64", "FLOAT64"):
                assert col["measurement_unit"], (
                    f"{table}.{col['name']}: numeric column without a measurement unit"
                )
            for lang in ("pt", "en", "es"):
                d = col[f"description_{lang}"]
                assert d and d[0].isupper(), (
                    f"{table}.{col['name']}: description_{lang} must start uppercase"
                )
                assert not d.endswith("."), (
                    f"{table}.{col['name']}: description_{lang} must not end with a period"
                )
        path = ARCH / f"sheet_{table}.csv"
        # lineterminator is explicit: csv defaults to \r\n, which the
        # mixed-line-ending pre-commit hook then rewrites on every regeneration.
        with open(path, "w", encoding="utf-8", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=FIELDS, lineterminator="\n")
            w.writeheader()
            w.writerows(cols)
        print(f"wrote {path.name}: {len(cols)} columns")


if __name__ == "__main__":
    main()
