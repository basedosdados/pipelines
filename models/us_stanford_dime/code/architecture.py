# Source CSV header -> architecture column name, per table. Built from the
# original_name field so the cleaning step never restates the mapping.
def rename_map(table: str) -> dict[str, str]:
    """Return ``{source column: architecture column}`` for one table."""
    return {c[9]: c[0] for c in TABLES[table] if c[9] and "<" not in c[9]}


def column_names(table: str) -> list[str]:
    """Return the architecture column order for one table."""
    return [c[0] for c in TABLES[table]]


def column_types(table: str) -> dict[str, str]:
    """Return ``{column: bigquery_type}`` for one table."""
    return {c[0]: c[1] for c in TABLES[table]}


def write_all() -> None:
    """Write one architecture CSV per table."""
    ARCH_DIR.mkdir(parents=True, exist_ok=True)
    for table, cols in TABLES.items():
        path = ARCH_DIR / f"{table}.csv"
        with path.open("w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(HEADER)
            for c in cols:
                w.writerow(c)
        print(f"wrote {path.name} ({len(cols)} columns)")


if __name__ == "__main__":
    write_all()
