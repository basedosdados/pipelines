"""Architecture tables for us_stanford_dime (DIME v4.0).

The architecture is the single source of truth for column names, types,
descriptions and ordering. Cleaning, dbt models and backend metadata are all
generated from it.

Column order follows the Data Basis style manual: partition columns first,
then identifiers, then descriptive columns. Names are English because the
data and its documentation are English (see .claude/rules/data-basis-style.md),
and identifiers take the ``_id`` suffix rather than the Portuguese ``id_``
prefix.

Types follow arithmetic meaning, not source storage: a column is INT64/FLOAT64
only when summing or averaging it is meaningful and it has a real measurement
unit. Coded values (party codes, transaction codes, 0/1 flags) are STRING and
carry ``covered_by_dictionary = yes`` when the ``dicionario`` table defines
their labels.

Run ``python architecture.py`` to (re)write the CSVs under ``architecture/``.
"""

