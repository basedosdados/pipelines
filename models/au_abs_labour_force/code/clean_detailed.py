def build_unemployment_duration() -> pd.DataFrame:
    """UM2 (state, no age) + UM3 (national, by age), merged on a total sentinel.

    The house pattern already used by the sibling `labour_force_status`, which
    merges the state cube with the by-age national cube the same way.
    """
    measures = {
        M_UNEMP: "unemployed_total",
        M_ULFT: "unemployed_looked_for_full_time",
        M_ULPT: "unemployed_looked_for_part_time",
        M_WEEKS: "weeks_searching",
    }

    um2 = add_time(load_cube("UM2"), quarterly=False)
    um2 = um2.rename(columns={H_STT: "geography", H_DURATION: "duration_band"})
    um2["age_group"] = "total"
    um2 = scale(um2, measures)

    um3 = add_time(load_cube("UM3"), quarterly=False)
    um3 = um3.rename(columns={H_AGE: "age_group", H_DURATION: "duration_band"})
    um3["geography"] = "Australia"
    um3 = scale(um3, measures)

    return pd.concat([um2, um3], ignore_index=True)


