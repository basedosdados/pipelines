def validate(table: str, df: pd.DataFrame) -> dict[str, float]:
    """Check shape, grain uniqueness and key nullability; measure sparsity."""
    arch = read_arch(table)
    order = [a["name"] for a in arch]
    missing = [c for c in order if c not in df.columns]
    extra = [c for c in df.columns if c not in order]
    if missing or extra:
        raise ValueError(f"{table}: missing={missing} extra={extra}")

    want = EXPECTED_TABLE_ROWS[table]
    if len(df) != want:
        raise ValueError(f"{table}: {len(df):,} rows, expected {want:,}")

    dup = df.duplicated(subset=GRAIN[table]).sum()
    if dup:
        raise ValueError(
            f"{table}: {dup:,} duplicate rows on grain {GRAIN[table]}"
        )

    for col in GRAIN[table]:
        n_null = int(df[col].isna().sum())
        if n_null:
            raise ValueError(
                f"{table}.{col}: {n_null:,} NULLs in a grain column"
            )

    frac = {c: round(float(df[c].notna().mean()), 4) for c in order}
    sparse = {c: v for c, v in frac.items() if v < 0.10}
    log.info(
        f"{table}: {len(df):,} rows OK; "
        f"sparse columns (<10% non-null): {sparse or 'none'}"
    )
    return frac


def write_partitioned(df: pd.DataFrame, table: str, output_dir: Path) -> Path:
    """Write a table as all-STRING Snappy parquet, hive-partitioned by year.

    Staging is all-STRING by Data Basis convention (`gcs.py::dump_header`
    stringifies the header BigQuery infers the staging schema from). Values pass
    through the architecture's real types first — so year serialises as "1984"
    not "1984.0" — then cast to string via arrow, never astype(str), which
    renders NULL as the literal "nan" and defeats the dbt safe_cast.
    """
    arch = read_arch(table)
    order = [a["name"] for a in arch]
    typed = pa.schema(
        [pa.field(a["name"], PA[a["bigquery_type"]]) for a in arch]
    )
    string_schema = pa.schema([pa.field(a["name"], pa.string()) for a in arch])
    out = df[order].copy()
    tdir = output_dir / table
    total = 0
    for year, g in out.groupby("year", sort=True):
        pdir = tdir / f"year={int(year)}"
        pdir.mkdir(parents=True, exist_ok=True)
        at = pa.Table.from_pandas(g, schema=typed, preserve_index=False)
        at = at.cast(string_schema)
        pq.write_table(at, pdir / "data.parquet", compression="snappy")
        total += len(g)
    log.info(f"{table}: {total:,} rows -> {tdir}")
    return tdir


