def build_employment_industry_hours() -> pd.DataFrame:
    parts = []
    for cube, (measure, band_header) in HOURS_CUBES.items():
        df = add_time(load_cube(cube), quarterly=True)
        df = df.rename(
            columns={
                band_header: "hours_band",
                H_DIVISION: "industry_division",
            }
        )
        bad = set(df["hours_band"].dropna().unique()) & ZERO_LABEL_VARIANTS
        if not bad:
            raise ValueError(
                f"{cube}: no zero-hours label found among the bands"
            )
        df["hours_band"] = df["hours_band"].replace(
            {v: ZERO_LABEL for v in ZERO_LABEL_VARIANTS}
        )
        df["hours_measure"] = measure
        df["industry_division_code"] = map_strict(
            df["industry_division"],
            ANZSIC_DIVISION_CODE,
            f"{cube} ANZSIC division",
        )
        parts.append(emp_measures(df))
    return pd.concat(parts, ignore_index=True)


