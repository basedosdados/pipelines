def read_arch(table: str) -> list[dict[str, str]]:
    """Architecture rows for one table, in column order."""
    with (ARCH / f"{table}.csv").open() as fh:
        return list(csv.DictReader(fh))


def load_cube(cube: str) -> pd.DataFrame:
    """Read a cube's ``Data 1`` fact sheet into a DataFrame.

    The header is not row 0: three ABS banner rows sit above it. It is located
    by scanning the first eight rows for the one whose first cell is the time
    column, then everything below it whose first cell is a real period is data.
    Trailing all-empty columns and the copyright cell are dropped.
    """
    path = INPUT / f"{cube}.xlsx"
    if not path.exists():
        raise FileNotFoundError(path)
    wb = openpyxl.load_workbook(path, read_only=True, data_only=True)
    if "Data 1" not in wb.sheetnames:
        raise ValueError(f"{cube}: no 'Data 1' sheet (has {wb.sheetnames})")
    ws = wb["Data 1"]
    it = ws.iter_rows(values_only=True)

    header: list[str] | None = None
    for i, row in enumerate(it):
        first = row[0]
        if isinstance(first, str) and first.strip() in (H_TIME_Q, H_TIME_M):
            header = [str(c).strip() for c in row if c is not None]
            break
        if i >= 7:
            break
    if header is None:
        raise ValueError(f"{cube}: header row not found in the first 8 rows")

    ncol = len(header)
    data = [row[:ncol] for row in it if row and _is_period(row[0])]
    wb.close()

    df = pd.DataFrame(data, columns=header)
    n = len(df)
    want = EXPECTED_CUBE_ROWS[cube]
    if n != want:
        raise ValueError(
            f"{cube}: {n:,} data rows on 'Data 1', expected {want:,}"
        )
    log.info(f"{cube}: {n:,} rows, {ncol} columns")
    return df


def _is_period(value: object) -> bool:
    """True for a real reference period cell (drops the copyright footer)."""
    return hasattr(value, "year") and hasattr(value, "month")


def add_time(df: pd.DataFrame, quarterly: bool) -> pd.DataFrame:
    """Split the ABS period column into year, quarter (quarterly only), month."""
    col = H_TIME_Q if quarterly else H_TIME_M
    ts = pd.to_datetime(df[col])
    df = df.drop(columns=[col])
    df.insert(0, "month", ts.dt.month.astype("int64"))
    if quarterly:
        months = set(df["month"].unique())
        if not months <= {2, 5, 8, 11}:
            raise ValueError(
                f"unexpected mid-quarter months: {sorted(months)}"
            )
        df.insert(0, "quarter", ((df["month"] - 1) // 3 + 1).astype("int64"))
    df.insert(0, "year", ts.dt.year.astype("int64"))
    return df


def scale(df: pd.DataFrame, mapping: dict[str, str]) -> pd.DataFrame:
    """Rename the ABS measure columns and convert thousands to absolute units."""
    for src, dst in mapping.items():
        if src not in df.columns:
            raise KeyError(f"measure column missing: {src!r}")
        df[dst] = pd.to_numeric(df[src], errors="coerce") * THOUSANDS
        if dst != src:
            df = df.drop(columns=[src])
    return df


EMP_MEASURE_MAP = {
    M_EFT: "employed_full_time",
    M_EPT: "employed_part_time",
}


def emp_hours_map(df: pd.DataFrame) -> dict[str, str]:
    """Locate the two hours measures, whose names vary by cube."""
    ft = [
        c
        for c in df.columns
        if c.startswith("Number of hours") and "(employed full-time)" in c
    ]
    pt = [
        c
        for c in df.columns
        if c.startswith("Number of hours") and "(employed part-time)" in c
    ]
    if len(ft) != 1 or len(pt) != 1:
        raise ValueError(f"expected one hours column per FT/PT, got {ft} {pt}")
    return {ft[0]: "hours_worked_full_time", pt[0]: "hours_worked_part_time"}


def emp_measures(df: pd.DataFrame) -> pd.DataFrame:
    return scale(df, {**EMP_MEASURE_MAP, **emp_hours_map(df)})


def map_strict(
    series: pd.Series, mapping: dict[str, str], what: str
) -> pd.Series:
    """Map labels to codes, raising on any label the map does not cover."""
    observed = set(series.dropna().unique())
    unmapped = observed - set(mapping)
    if unmapped:
        raise ValueError(
            f"{what}: {len(unmapped)} unmapped label(s): {sorted(unmapped)[:5]}"
        )
    unused = set(mapping) - observed
    if unused:
        log.warning(
            f"{what}: {len(unused)} map entries unused: {sorted(unused)}"
        )
    return series.map(mapping)


def split_group_code(series: pd.Series) -> tuple[pd.Series, pd.Series]:
    """Split ABS's code-prefixed industry group label into code and label.

    Two prefix forms occur, both three characters wide. 272 labels carry a real
    ANZSIC three-digit group code ("011 Nursery and Floriculture Production").
    The other 19 are division-level not-further-defined residuals, which ABS
    codes as the division letter followed by 00 ("A00 Agriculture, Forestry and
    Fishing nfd") — one per ANZSIC division, asserted below.
    """
    m = series.str.extract(r"^(\d{3}|[A-Z]00)\s+(.+)$")
    bad = series[m[0].isna()].unique()
    if len(bad):
        raise ValueError(
            f"industry group labels without a recognised code prefix: "
            f"{sorted(bad)[:5]}"
        )
    letters = {c[0] for c in m[0].dropna().unique() if c[0].isalpha()}
    expected = set(ANZSIC_DIVISION_CODE.values())
    if letters != expected:
        raise ValueError(
            f"nfd residual division letters {sorted(letters)} do not match the "
            f"19 ANZSIC divisions {sorted(expected)}"
        )
    return m[0], m[1]


# ── per-table builders ───────────────────────────────────────────────────────
def division_from_group_code(codes: pd.Series) -> pd.Series:
    """Roll EQ06's group-level codes up to their ANZSIC division letter.

    EQ06 is the only cube that publishes industry at group level, so it is the
    only one without a division column of its own. Every other industry table
    carries ``industry_division_code``/``industry_division``; deriving them here
    keeps the largest table joinable to its siblings and aggregatable to the 19
    divisions.

    The 19 division-level ``nfd`` residuals already carry their letter (``A00``);
    the 272 real group codes are mapped by their subdivision, the first two
    digits. Raises if any code lands outside every range.
    """
    letters = codes.str[0].where(codes.str[0].str.isalpha())
    subdivision = pd.to_numeric(codes.str[:2], errors="coerce")
    for letter, (lo, hi) in ANZSIC_DIVISION_SUBDIVISIONS.items():
        letters = letters.mask(subdivision.between(lo, hi), letter)
    if letters.isna().any():
        orphans = sorted(codes[letters.isna()].unique())[:5]
        raise ValueError(
            f"industry group codes outside every ANZSIC subdivision range: "
            f"{orphans}"
        )
    return letters


def build_employment_industry() -> pd.DataFrame:
    df = add_time(load_cube("EQ06"), quarterly=True)
    df = df.rename(columns={H_STT: "geography"})
    code, label = split_group_code(df[H_GROUP])
    df["industry_group_code"] = code
    df["industry_group"] = label
    df["industry_division_code"] = division_from_group_code(code)
    division_label = {v: k for k, v in ANZSIC_DIVISION_CODE.items()}
    df["industry_division"] = df["industry_division_code"].map(division_label)
    df = df.drop(columns=[H_GROUP])
    df["sex"] = df[H_SEX].str.lower()
    return emp_measures(df.drop(columns=[H_SEX]))


