def loanflag(en_x, pt_x, es_x):
    return (
        f"Marker set to 'Yes' when the loan is {en_x}",
        f"Marcador definido como 'Sim' quando o empréstimo é {pt_x}",
        f"Marcador definido como 'Sí' cuando el préstamo es {es_x}",
    )


def ag_name(en_role, pt_role, es_role):
    return (
        f"Name of the {en_role}; pipe-delimited when multiple",
        f"Nome da(s) {pt_role}; separadas por barra vertical quando múltiplas",
        f"Nombre de la(s) {es_role}; separadas por barra vertical cuando son varias",
    )


def ag_type(en_role, pt_role, es_role):
    return (
        f"Type and country of origin of the {en_role}; pipe-delimited when multiple",
        f"Tipo e país de origem da(s) {pt_role}; separados por barra vertical quando múltiplos",
        f"Tipo y país de origen de la(s) {es_role}; separados por barra vertical cuando son varios",
    )


