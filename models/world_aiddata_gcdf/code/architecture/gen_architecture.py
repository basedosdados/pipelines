"""Single source of truth for the world_aiddata_gcdf architecture.

Generates the architecture CSV (BD schema) and, from the same spec, the column
order and type map consumed by clean.py and the dbt model. Columns are mapped to
the source workbook BY POSITION (first 126 columns of the ``GCDF_3.0`` sheet), so
minor punctuation differences in the source headers (curly vs. straight
apostrophes, hyphenation) never break the rename.

Dataset: AidData's Global Chinese Development Finance Dataset, Version 3.0.
One project/activity-level table (``projects``). English column names.
Descriptions in PT / EN / ES. Types follow arithmetic meaning:
INT64/FLOAT64 only for genuine quantities (each with a measurement unit where
one exists); every categorical/coded/flag field stays STRING. The categorical
fields store human-readable labels (e.g. Status="Completion", Flow Type="Loan"),
so no ``dicionario`` is required.
"""

