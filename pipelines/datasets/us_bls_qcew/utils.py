"""Download + cleaning transform for us_bls_qcew (shared by the one-shot
onboarding bootstrap in ``models/us_bls_qcew/code/`` and, later, the recurring
Prefect pipeline).

Pure functions (no Prefect) so they are importable and unit-testable. Column
order and BigQuery types come from the architecture CSVs (the single source of
truth), generated by ``models/us_bls_qcew/code/build_architecture.py``.

The QCEW singlefiles stack every aggregation level in one file; this transform
routes each row to a geographic-level table (national / state / county / metro)
by the ``agglvl_code``, which uses different schemes for NAICS and SIC. See
``constants.NAICS_AGGLVL_GEO`` / ``SIC_AGGLVL_GEO``.
"""

import concurrent.futures
import csv
import datetime
import logging
import shutil
import zipfile
from pathlib import Path

import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq
import requests

from pipelines.datasets.us_bls_qcew.constants import constants

log = logging.getLogger("us_bls_qcew")

PA = {"STRING": pa.string(), "INT64": pa.int64(), "FLOAT64": pa.float64()}

_UA = constants.USER_AGENT.value
_HEADERS = {"User-Agent": _UA, "Referer": constants.REFERER.value}
_ARCH = constants.ARCHITECTURE_DIR.value
_GEO_MAP = {
    "naics": constants.NAICS_AGGLVL_GEO.value,
    "sic": constants.SIC_AGGLVL_GEO.value,
}

# Canonicalize the establishment column: SIC files suffix it `_count`, NAICS
# files do not. One name per concept keeps NAICS and SIC architectures aligned.
_RENAME = {
    "qtrly_estabs_count": "qtrly_estabs",
    "annual_avg_estabs_count": "annual_avg_estabs",
}


# ── download ────────────────────────────────────────────────────────────────
def singlefile_url(classification: str, freq: str, year: int) -> str:
    """Return the singlefile zip URL for a classification/frequency/year."""
    seg = constants.FREQ_SEGMENT.value[freq]
    tmpl = (
        constants.NAICS_URL.value
        if classification == "naics"
        else constants.SIC_URL.value
    )
    return tmpl.format(year=year, freq=seg)


def download_singlefile(
    classification: str, freq: str, year: int, input_dir: Path
) -> Path:
    """Download and extract one singlefile CSV into ``input_dir``.

    Cached: if the extracted CSV already exists it is returned without a refetch.
    ``data.bls.gov`` requires a browser User-Agent (403 otherwise).

    Args:
        classification: ``"naics"`` or ``"sic"``.
        freq: ``"quarterly"`` or ``"annual"``.
        year: Data year.
        input_dir: Directory to download into; created if absent.

    Returns:
        Path to the extracted ``.csv``.
    """
    dest_dir = input_dir / classification / freq
    dest_dir.mkdir(parents=True, exist_ok=True)
    marker = dest_dir / f"{year}.csv"
    if marker.exists() and marker.stat().st_size > 0:
        return marker
    url = singlefile_url(classification, freq, year)
    log.info(f"download {classification}/{freq}/{year} <- {url}")
    # Stream to disk: singlefile zips reach 200+ MB (recent NAICS quarterly), and
    # an in-memory fetch truncates on the large, slow transfers.
    zip_path = dest_dir / f"{year}.zip"
    with requests.get(url, headers=_HEADERS, timeout=600, stream=True) as r:
        r.raise_for_status()
        with open(zip_path, "wb") as fh:
            for chunk in r.iter_content(chunk_size=1 << 20):
                fh.write(chunk)
    with zipfile.ZipFile(zip_path) as z:
        name = next(n for n in z.namelist() if n.lower().endswith(".csv"))
        with z.open(name) as src, open(marker, "wb") as dst:
            shutil.copyfileobj(src, dst)
    zip_path.unlink()
    return marker


def singlefile_available(classification: str, freq: str, year: int) -> bool:
    """Return whether the (classification, freq, year) singlefile is published.

    Probes the URL with a streaming GET and inspects only the status code — the
    body is never read, so a leading-edge year that BLS has not yet published
    (404) is detected cheaply. ``data.bls.gov`` requires a browser User-Agent.
    """
    url = singlefile_url(classification, freq, year)
    with requests.get(url, headers=_HEADERS, timeout=120, stream=True) as r:
        return r.status_code == 200


def latest_available_year(
    classification: str, freq: str, floor: int, ceiling: int | None = None
) -> int:
    """Highest published year for a (classification, freq), probing downward.

    QCEW publishes each year's quarterly singlefile before that year's annual
    singlefile (the annual file needs all four quarters), so the latest available
    year differs between the two frequencies. Probe each frequency separately.

    Args:
        classification: ``"naics"`` or ``"sic"``.
        freq: ``"quarterly"`` or ``"annual"``.
        floor: earliest year to consider (the coverage start).
        ceiling: newest year to probe; defaults to the current calendar year.

    Returns:
        The greatest year in ``[floor, ceiling]`` whose singlefile exists.

    Raises:
        RuntimeError: if no year in the range is published.
    """
    if ceiling is None:
        ceiling = datetime.date.today().year
    for year in range(ceiling, floor - 1, -1):
        if singlefile_available(classification, freq, year):
            return year
    raise RuntimeError(
        f"no published {classification}/{freq} singlefile in {floor}..{ceiling}"
    )


def peek_max_quarter(
    classification: str, freq: str, year: int, input_dir: Path
) -> int:
    """Return the greatest quarter (1-4) present in a quarterly singlefile.

    Downloads the singlefile (cached) and scans only its ``qtr`` column, so a new
    quarter appended to an existing year's file is detected without a full clean.
    Within one calendar year QCEW adds quarters incrementally — a mid-year file
    may hold only Q1-Q2 — so the max quarter, not merely the year, drives the poll.
    """
    path = download_singlefile(classification, freq, year, input_dir)
    col = pd.read_csv(
        path,
        dtype=str,
        na_filter=False,
        usecols=lambda c: c.strip() == "qtr",
    ).iloc[:, 0]
    return int(pd.to_numeric(col.str.strip(), errors="coerce").max())


def source_max_year_month(
    input_dir: Path, floor: int, ceiling: int | None = None
) -> str:
    """Latest NAICS quarterly period as ``"YYYY-MM"`` for the source poll.

    A quarter is mapped to its end month (``quarter * 3``) — Q1→03, Q2→06,
    Q3→09, Q4→12 — matching the ``DATE(year, quarter*3, 1)`` convention that
    ``register_table_materialization`` uses to read the table's max coverage date
    from BigQuery. Keeping the two aligned makes the poll comparison and the
    committed source ``Update`` consistent with the stored coverage end.
    """
    year = latest_available_year("naics", "quarterly", floor, ceiling)
    quarter = peek_max_quarter("naics", "quarterly", year, input_dir)
    return f"{year}-{quarter * 3:02d}"


def download_titles(input_dir: Path) -> Path:
    """Download the NAICS and SIC code-title CSVs used to build the dicionario.

    Returns the ``input_dir/titles`` directory holding ``{,sic_}<kind>_titles.csv``.
    """
    tdir = input_dir / "titles"
    tdir.mkdir(parents=True, exist_ok=True)
    for kind in ("agglevel", "area", "industry", "ownership", "size"):
        for p in ("", "sic_"):
            fname = f"{p}{kind}_titles.csv"
            dest = tdir / fname
            if dest.exists() and dest.stat().st_size > 0:
                continue
            url = constants.TITLE_URL.value.format(kind=kind, p=p)
            r = requests.get(url, headers=_HEADERS, timeout=120)
            r.raise_for_status()
            dest.write_bytes(r.content)
    return tdir


# ── schema ──────────────────────────────────────────────────────────────────
def read_arch(table: str) -> list[dict]:
    """Read a table's architecture CSV — the schema source of truth."""
    with open(_ARCH / f"{table}.csv", newline="") as fh:
        return list(csv.DictReader(fh))


def data_tables() -> list[str]:
    """All 16 data-table slugs, ``{class}_{freq}_{geo}``."""
    return [
        f"{c}_{f}_{g}"
        for c in constants.CLASSES.value
        for f in constants.FREQS.value
        for g in constants.GEOS.value
    ]


# ── transform ───────────────────────────────────────────────────────────────
# Row-chunk size for streaming a singlefile. Recent NAICS quarterly files reach
# ~15M rows x 42 columns (~2 GB on disk); loading one whole into pandas as
# strings needs 10+ GB and OOM-kills a 16 GB machine. Streaming caps peak memory
# at one chunk regardless of file size.
CHUNK_ROWS = 500_000

# Cache architecture schemas (read once per table, not once per chunk).
_ARCH_CACHE: dict = {}


def _arch(table: str) -> list[dict]:
    if table not in _ARCH_CACHE:
        _ARCH_CACHE[table] = read_arch(table)
    return _ARCH_CACHE[table]


def _write_chunk(
    frame: pd.DataFrame, table: str, year: int, suffix: int, output_dir: Path
) -> int:
    """Type-coerce one geo/year chunk and append it as all-STRING parquet.

    Values pass through the architecture's real types first (so ``year``
    serializes as ``"1990"`` not ``"1990.0"`` and NULLs stay NULL), then cast to
    an all-string schema via arrow — never ``astype(str)``, which renders NULL as
    ``"nan"``. Staging is all-STRING by house convention; the dbt model
    ``safe_cast``s every column. See [[project_dump_header_parquet_bug]]. Each
    chunk is a separate ``data_<suffix>.parquet`` in the year partition; BigQuery
    reads every parquet in the directory.
    """
    arch = _arch(table)
    d = frame.copy()
    for a in arch:
        col, t = a["name"], a["bigquery_type"]
        s = (
            d[col]
            .astype("string")
            .str.strip()
            .replace({"": pd.NA, "-": pd.NA})
        )
        if t == "INT64":
            d[col] = pd.to_numeric(s, errors="coerce").astype("Int64")
        elif t == "FLOAT64":
            d[col] = pd.to_numeric(s, errors="coerce").astype("float64")
        else:
            d[col] = s
    typed = pa.schema(
        [pa.field(a["name"], PA[a["bigquery_type"]]) for a in arch]
    )
    strung = pa.schema([pa.field(a["name"], pa.string()) for a in arch])
    pdir = output_dir / table / f"year={int(year)}"
    pdir.mkdir(parents=True, exist_ok=True)
    at = pa.Table.from_pandas(
        d[[a["name"] for a in arch]], schema=typed, preserve_index=False
    ).cast(strung)
    pq.write_table(
        at, pdir / f"data_{suffix:04d}.parquet", compression="snappy"
    )
    return len(d)


def clean_year(
    classification: str,
    freq: str,
    year: int,
    input_dir: Path,
    output_dir: Path,
    prune_input: bool = False,
) -> dict:
    """Stream one singlefile into per-geographic-level parquet, chunk by chunk.

    Reads the CSV in ``CHUNK_ROWS`` row chunks; each chunk is routed to the four
    geographic tables by ``agglvl_code`` and written as a ``data_<n>.parquet`` in
    that table's ``year=<year>`` partition. Peak memory is one chunk, so a 15M-row
    file cleans in bounded RAM. Stale parquet from a previous run of the same year
    is cleared first so re-runs do not double-count.

    Args:
        classification: ``"naics"`` or ``"sic"``.
        freq: ``"quarterly"`` or ``"annual"``.
        year: Data year.
        input_dir: Root of downloaded files (downloads on demand).
        output_dir: Root output directory.

    Returns:
        ``{table_slug: rows_written}`` for the geo tables touched.
    """
    # Resumable full-history runs: skip a year already finished on a prior run
    # (its CSV was pruned), so a restart re-downloads nothing already done.
    marker = output_dir / ".done" / f"{classification}_{freq}_{year}"
    if prune_input and marker.exists():
        log.info(f"skip {classification}/{freq}/{year} (already done)")
        return {}

    path = download_singlefile(classification, freq, year, input_dir)
    geomap = _GEO_MAP[classification]
    # clear stale partitions for this (classification, freq, year)
    for g in constants.GEOS.value:
        pdir = (
            output_dir / f"{classification}_{freq}_{g}" / f"year={int(year)}"
        )
        if pdir.exists():
            for old in pdir.glob("*.parquet"):
                old.unlink()

    counts: dict = {}
    unmapped: set = set()
    reader = pd.read_csv(
        path, dtype=str, na_filter=False, chunksize=CHUNK_ROWS
    )
    for ci, chunk in enumerate(reader):
        chunk.columns = [c.strip() for c in chunk.columns]
        chunk = chunk.rename(columns=_RENAME)
        chunk["agglvl_code"] = chunk["agglvl_code"].str.strip().str.zfill(2)
        geo = chunk["agglvl_code"].map(geomap)
        unmapped |= set(chunk["agglvl_code"][geo.isna()].unique())
        for g in constants.GEOS.value:
            sub = chunk[geo == g]
            if sub.empty:
                continue
            table = f"{classification}_{freq}_{g}"
            s = sub.copy()
            if g == "state":
                s["id_state"] = s["area_fips"].str.strip().str[:2]
            cols = [a["name"] for a in _arch(table)]
            missing = [c for c in cols if c not in s.columns]
            if missing:
                raise KeyError(f"{table}: source missing columns {missing}")
            # Drop exact-duplicate rows. Some singlefiles repeat a block of rows
            # verbatim — the 1982 SIC file writes area 57000's 24-key state block
            # twice, back-to-back — which would break the table's uniqueness key.
            # The repeat is consecutive (within one 500k-row chunk), so a
            # per-chunk dedup removes it; it is a no-op for every clean table.
            frame = s[cols].drop_duplicates()
            counts[table] = counts.get(table, 0) + _write_chunk(
                frame, table, year, ci, output_dir
            )
            del s, sub, frame
        del chunk, geo
    if unmapped:
        log.warning(
            f"{classification}/{freq}/{year}: unmapped agglvl {sorted(unmapped)}"
        )
    for table, n in counts.items():
        log.info(f"{table} [{year}]: {n:,} rows")
    if prune_input:
        # Full-history backfill: drop the multi-GB CSV once cleaned so input never
        # accumulates (and does not sync to Dropbox). The parquet output remains.
        path.unlink(missing_ok=True)
        marker.parent.mkdir(parents=True, exist_ok=True)
        marker.write_text("")
    return counts


# ── dicionario ──────────────────────────────────────────────────────────────
def _titles(tdir: Path, fname: str, code_col: str, name_col: str) -> dict:
    df = pd.read_csv(tdir / fname, dtype=str, na_filter=False)
    df.columns = [c.strip() for c in df.columns]
    return {r[code_col].strip(): r[name_col].strip() for _, r in df.iterrows()}


def _area_class(code: str) -> str:
    """Classify an area_fips code as national / metro / state / county."""
    c = code.strip()
    if c.startswith("US") or c.startswith("U"):
        return "national"
    if c[:1] in ("C", "M"):
        return "metro"
    if c[2:] == "000":
        return "state"
    return "county"


def build_dicionario(input_dir: Path, output_dir: Path) -> Path:
    """Build the ``dicionario`` table: coded columns → human-readable labels.

    Covers ``own_code``, ``agglvl_code``, ``size_code`` and ``industry_code`` for
    every data table, and ``area_fips`` for the ``*_national`` and ``*_metro``
    tables (county/state area codes resolve via the geography directory instead).
    Column names stay Portuguese (``id_tabela``, ``nome_coluna``, ``chave``,
    ``cobertura_temporal``, ``valor``) — the platform's dictionary renderer
    expects that schema — even though this dataset is English.
    """
    tdir = download_titles(input_dir)
    per_class = {}
    for cls, p in (("naics", ""), ("sic", "sic_")):
        ind_code = "csv_industry_code" if cls == "sic" else "industry_code"
        # Column names differ across the two title-file families: NAICS ownership
        # uses own_code/own_title, SIC uses ownership_code/ownership_title; SIC
        # industry codes live in csv_industry_code.
        own_code_col = "ownership_code" if cls == "sic" else "own_code"
        own_title_col = "ownership_title" if cls == "sic" else "own_title"
        area = _titles(tdir, f"{p}area_titles.csv", "area_fips", "area_title")
        per_class[cls] = {
            "own_code": _titles(
                tdir,
                f"{p}ownership_titles.csv",
                own_code_col,
                own_title_col,
            ),
            "agglvl_code": _titles(
                tdir, f"{p}agglevel_titles.csv", "agglvl_code", "agglvl_title"
            ),
            "size_code": _titles(
                tdir, f"{p}size_titles.csv", "size_code", "size_title"
            ),
            "industry_code": _titles(
                tdir, f"{p}industry_titles.csv", ind_code, "industry_title"
            ),
            "_area": area,
        }

    rows = []
    for table in data_tables():
        cls = "naics" if table.startswith("naics") else "sic"
        geo = table.rsplit("_", 1)[1]
        maps = per_class[cls]
        for col in ("own_code", "agglvl_code", "size_code", "industry_code"):
            for key, label in maps[col].items():
                rows.append((table, col, key, None, label))
        if geo in ("national", "metro"):
            for key, label in maps["_area"].items():
                if _area_class(key) == geo:
                    rows.append((table, "area_fips", key, None, label))

    df = pd.DataFrame(
        rows,
        columns=[
            "id_tabela",
            "nome_coluna",
            "chave",
            "cobertura_temporal",
            "valor",
        ],
    )
    schema = pa.schema(
        [
            pa.field(a["name"], PA[a["bigquery_type"]])
            for a in read_arch("dicionario")
        ]
    )
    out = output_dir / "dicionario"
    out.mkdir(parents=True, exist_ok=True)
    pq.write_table(
        pa.Table.from_pandas(df, schema=schema, preserve_index=False),
        out / "data.parquet",
        compression="snappy",
    )
    log.info(f"dicionario: {len(df):,} rows -> {out}")
    return out


# ── orchestration ───────────────────────────────────────────────────────────
def clean_all(
    years: dict,
    input_dir: Path,
    output_dir: Path,
    prune_input: bool = False,
    download_workers: int = 1,
) -> dict:
    """Clean the requested years for every class/freq/geo table + the dicionario.

    Downloads and cleaning are separable: a download is pure I/O, whereas
    cleaning one 15M-row singlefile is the memory-bounded step (streamed in
    ``CHUNK_ROWS`` chunks). With ``download_workers > 1`` the downloads run
    concurrently and feed a **single serial cleaner** through a sliding window of
    at most ``download_workers`` in-flight fetches. Two invariants follow:

    * Cleaning is never parallel, so peak memory stays one chunk regardless of
      worker count — the same bound that makes a 15M-row file safe on a 16 GB box.
    * At most ``download_workers`` downloaded CSVs sit ahead of the cleaner, so
      with ``prune_input`` the pruned CSVs never accumulate on disk.

    The result is identical for any ``download_workers`` — only wall-clock (which
    is download-bound) changes. The recurring Prefect pipeline calls this same
    function, so it inherits the identical parallelism with no Prefect-specific
    concurrency machinery.

    Args:
        years: ``{"naics": [...], "sic": [...]}`` — which data years to process.
        input_dir: Root of downloaded files.
        output_dir: Root output directory.
        prune_input: delete each singlefile CSV once cleaned (full-history runs).
        download_workers: concurrent downloads prefetched ahead of the cleaner
            (``1`` = fully sequential, the original behavior).

    Returns:
        Mapping ``{table_slug: total_rows_written}`` plus ``dicionario``.
    """
    tasks = [
        (cls, freq, year)
        for cls in constants.CLASSES.value
        for freq in constants.FREQS.value
        for year in years[cls]
    ]
    # Resumability: drop already-finished tasks up front (their CSV was pruned on
    # a prior run) so restarts re-download nothing already cleaned.
    if prune_input:
        tasks = [
            t
            for t in tasks
            if not (output_dir / ".done" / f"{t[0]}_{t[1]}_{t[2]}").exists()
        ]

    written: dict = {}

    def _accumulate(counts: dict) -> None:
        for table, n in counts.items():
            written[table] = written.get(table, 0) + n

    if download_workers <= 1:
        for cls, freq, year in tasks:
            _accumulate(
                clean_year(cls, freq, year, input_dir, output_dir, prune_input)
            )
    else:
        # Prefetch downloads in a sliding window; clean in task order. At step i
        # we wait only for task i's download (a cache hit inside clean_year),
        # having already scheduled tasks up to i+window, so downloads i+1..i+window
        # transfer in parallel while task i cleans. clean_year re-invokes
        # download_singlefile, which returns the already-cached CSV immediately.
        window = download_workers
        with concurrent.futures.ThreadPoolExecutor(
            max_workers=download_workers
        ) as ex:
            futures: dict = {}
            for i in range(min(window, len(tasks))):
                c, f, y = tasks[i]
                futures[i] = ex.submit(download_singlefile, c, f, y, input_dir)
            for i, (cls, freq, year) in enumerate(tasks):
                futures[i].result()  # ensure this file finished downloading
                nxt = i + window
                if nxt < len(tasks):
                    c, f, y = tasks[nxt]
                    futures[nxt] = ex.submit(
                        download_singlefile, c, f, y, input_dir
                    )
                _accumulate(
                    clean_year(
                        cls, freq, year, input_dir, output_dir, prune_input
                    )
                )
                del futures[i]

    build_dicionario(input_dir, output_dir)
    written["dicionario"] = "built"
    return written


def clean_naics_full_history(
    input_dir: Path,
    output_dir: Path,
    floor: int,
    ceiling: int | None = None,
    download_workers: int = 1,
) -> dict:
    """Rebuild the full NAICS history (both frequencies) into partitioned parquet.

    The recurring pipeline refreshes only the NAICS tables — SIC is frozen
    (1975-2000) and never republished, so it is excluded here. QCEW revises prior
    quarters on every release, and ``upload_to_gcs`` overwrites the whole staging
    table, so each run re-cleans the entire NAICS history rather than a single
    partition.

    The quarterly and annual latest years differ (a year's annual singlefile is
    published only after its four quarters), so the two frequencies are probed
    separately. Years where both frequencies exist go through :func:`clean_all`;
    any leading years that have a quarterly file but not yet an annual file are
    cleaned quarterly-only via :func:`clean_year`, so the newest quarter is
    ingested without waiting up to a year for its annual counterpart.

    ``prune_input=True`` throughout: each multi-GB CSV is deleted once cleaned, so
    a worker's disk holds at most ``download_workers`` singlefiles at a time.

    Args:
        input_dir: Root of downloaded files.
        output_dir: Root output directory.
        floor: earliest NAICS year (coverage start, 1990).
        ceiling: newest year to probe; defaults to the current calendar year.
        download_workers: concurrent downloads prefetched ahead of the cleaner.

    Returns:
        ``{table_slug: total_rows_written}`` for the 8 NAICS tables + dicionario.
    """
    qtrly_latest = latest_available_year("naics", "quarterly", floor, ceiling)
    annual_latest = latest_available_year("naics", "annual", floor, ceiling)
    log.info(
        f"NAICS latest available: quarterly={qtrly_latest} annual={annual_latest}"
    )

    written = clean_all(
        {"naics": list(range(floor, annual_latest + 1)), "sic": []},
        input_dir,
        output_dir,
        prune_input=True,
        download_workers=download_workers,
    )

    # Leading years with a quarterly file but no annual file yet.
    for year in range(annual_latest + 1, qtrly_latest + 1):
        counts = clean_year(
            "naics", "quarterly", year, input_dir, output_dir, prune_input=True
        )
        for table, n in counts.items():
            base = written.get(table, 0)
            written[table] = (base if isinstance(base, int) else 0) + n
    return written
